import { useEffect, useRef, useState } from "react";
import { PlanForm } from "./components/PlanForm";
import { Results } from "./components/Results";
import { ApiError, requestPlan } from "./api";
import { serverErrorsToForm, type FormErrors } from "./formUtils";
import { loadSaved, savePlan, toggleChecked } from "./storage";
import type { PlanRequest, PlanResponse } from "../shared/schema";

interface Result {
  request: PlanRequest;
  plan: PlanResponse;
}

export default function App() {
  const [saved] = useState(() => loadSaved());
  const [result, setResult] = useState<Result | null>(
    saved ? { request: saved.request, plan: saved.plan } : null,
  );
  const [checked, setChecked] = useState<string[]>(saved?.checked ?? []);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [serverErrors, setServerErrors] = useState<FormErrors>({});
  const focusResults = useRef(false);

  useEffect(() => {
    if (result) savePlan({ request: result.request, plan: result.plan, checked });
  }, [result, checked]);

  useEffect(() => {
    if (!focusResults.current || !result) return;
    focusResults.current = false;
    const heading = document.getElementById("results-heading");
    heading?.focus();
    heading?.scrollIntoView({ block: "start" });
  }, [result]);

  async function handleSubmit(request: PlanRequest) {
    setBusy(true);
    setError(null);
    setServerErrors({});
    try {
      const plan = await requestPlan(request);
      focusResults.current = true;
      setChecked([]);
      setResult({ request, plan });
    } catch (caught) {
      if (caught instanceof ApiError) {
        setError(caught.message);
        setServerErrors(serverErrorsToForm(caught.fieldErrors));
      } else {
        setError("Something went wrong. Please try again.");
      }
    } finally {
      setBusy(false);
    }
  }

  function handleEdit() {
    const field = document.getElementById("eventDate");
    field?.scrollIntoView({ block: "center" });
    field?.focus();
  }

  return (
    <>
      <a className="skip-link" href="#main">
        Skip to the planner
      </a>
      <header className="site-header">
        <div className="container">
          <h1>PlanPilot</h1>
          <p className="tagline">
            AI event planner for weddings, birthdays and community events in India.
          </p>
        </div>
      </header>

      <main id="main" tabIndex={-1} className="container">
        <section className="card no-print" aria-labelledby="form-title">
          <h2 id="form-title">Tell us about your event</h2>
          <p className="panel-intro">
            One form in, a full plan out: budget, timeline, vendors and ideas.
          </p>
          <PlanForm
            initial={result?.request ?? null}
            busy={busy}
            serverErrors={serverErrors}
            onSubmit={handleSubmit}
          />
        </section>

        <div className="status no-print" role="status" aria-live="polite">
          {busy ? (
            <>
              <span className="spinner" aria-hidden="true" />
              Building your plan. This takes about 10 to 20 seconds.
            </>
          ) : null}
        </div>

        {error ? (
          <div className="alert no-print" role="alert">
            {error}
          </div>
        ) : null}

        {result ? (
          <Results
            request={result.request}
            plan={result.plan}
            checked={checked}
            onToggle={(id) => setChecked((previous) => toggleChecked(previous, id))}
            onEdit={handleEdit}
          />
        ) : null}
      </main>

      <footer className="site-footer no-print">
        <div className="container">
          Plans are generated by Google Gemini and saved only in this browser. Always confirm prices
          with vendors.
        </div>
      </footer>
    </>
  );
}
